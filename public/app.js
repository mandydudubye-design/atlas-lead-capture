let currentLang = detectLanguage();
let lastWaUrl = "#";
let lastMessage = "";

function detectLanguage() {
  const saved = localStorage.getItem("lead-lang");
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("zh")) return "zh";
  return "en";
}

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.fr[key] || key;
}

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("lead-lang", lang);
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  document.title = t("meta.title");
  document.querySelector('meta[name="description"]').setAttribute("content", t("meta.description"));

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });

  fillSelects();
  updateContactLinks();
}

function fillSelects() {
  Object.entries(SELECTS).forEach(([id, config]) => {
    const select = document.getElementById(id);
    if (!select) return;
    const previous = select.value;
    select.innerHTML = "";
    config.values.forEach((value) => {
      const option = document.createElement("option");
      option.value = value;
      option.textContent = t(`${config.prefix}.${value}`);
      select.appendChild(option);
    });
    select.value = previous || config.default;
  });
}

function sanitizeNumber(value) {
  return String(value || "").replace(/\D/g, "");
}

function getWhatsAppNumber() {
  const fromQuery = sanitizeNumber(new URLSearchParams(location.search).get("wa"));
  if (fromQuery.length >= 8) return fromQuery;
  return sanitizeNumber(window.SITE_CONFIG.whatsappNumber);
}

function waUrl(message, numberOverride) {
  const number = numberOverride || getWhatsAppNumber();
  return `https://wa.me/${number}?text=${encodeURIComponent(message || "")}`;
}

function updateContactLinks() {
  const generic = t("msg.generic");
  const url = waUrl(generic);
  lastWaUrl = url;
  document.querySelectorAll("[data-wa-link]").forEach((el) => {
    el.setAttribute("href", url);
  });
  document.getElementById("emailLink").setAttribute("href", `mailto:${window.SITE_CONFIG.email}`);
  document.getElementById("facebookLink").setAttribute("href", window.SITE_CONFIG.facebookUrl);
}

function selectLabel(select) {
  const config = SELECTS[select.id];
  if (!config || !select.value) return "";
  return t(`${config.prefix}.${select.value}`);
}

function getFieldMessages() {
  document.querySelectorAll(".field").forEach((field) => {
    field.classList.remove("is-invalid");
    const msg = field.querySelector(".field-message");
    if (msg) msg.remove();
  });
}

function markInvalid(input, message) {
  const field = input.closest(".field");
  field.classList.add("is-invalid");
  let msg = field.querySelector(".field-message");
  if (!msg) {
    msg = document.createElement("p");
    msg.className = "field-message";
    field.appendChild(msg);
  }
  msg.textContent = message;
}

function validateForm(form) {
  getFieldMessages();
  let valid = true;
  let firstInvalid = null;

  ["name", "whatsapp", "product"].forEach((name) => {
    const input = form.elements[name];
    if (!input.value.trim()) {
      markInvalid(input, t("form.required"));
      valid = false;
      firstInvalid = firstInvalid || input;
    }
  });

  const category = form.elements.category;
  if (!category.value) {
    markInvalid(category, t("form.required"));
    valid = false;
    firstInvalid = firstInvalid || category;
  }

  const whatsapp = form.elements.whatsapp;
  if (whatsapp.value.trim() && !/^\+?[\d\s().-]{8,20}$/.test(whatsapp.value.trim())) {
    markInvalid(whatsapp, t("form.whatsapp"));
    valid = false;
    firstInvalid = firstInvalid || whatsapp;
  }

  if (firstInvalid) firstInvalid.focus();
  return valid;
}

function collectData(form) {
  const value = (name) => form.elements[name].value.trim();
  const params = new URLSearchParams(location.search);
  const source = params.get("utm_source") || params.get("source") || (document.referrer ? document.referrer.slice(0, 200) : "");
  return {
    name: value("name"),
    company: value("company"),
    whatsapp: value("whatsapp"),
    city: value("city"),
    category: form.elements.category.value,
    categoryLabel: selectLabel(form.elements.category),
    product: value("product"),
    quantity: value("quantity"),
    budget: value("budget"),
    customs: form.elements.customs.value,
    customsLabel: selectLabel(form.elements.customs),
    delivery: form.elements.delivery.value,
    deliveryLabel: selectLabel(form.elements.delivery),
    lang: currentLang,
    source
  };
}

function buildMessage(data) {
  const lines = [
    t("msg.prefix"),
    "",
    `- ${t("label.name")}: ${data.name}`,
    `- ${t("label.company")}: ${data.company || ""}`,
    `- ${t("label.whatsapp")}: ${data.whatsapp}`,
    `- ${t("label.city")}: ${data.city || ""}`,
    `- ${t("label.category")}: ${data.categoryLabel}`,
    `- ${t("label.product")}: ${data.product}`,
    `- ${t("label.quantity")}: ${data.quantity || ""}`,
    `- ${t("label.budget")}: ${data.budget || ""}`,
    `- ${t("label.customs")}: ${data.customsLabel}`,
    `- ${t("label.delivery")}: ${data.deliveryLabel}`
  ];
  return lines.join("\n");
}

async function backupToFeishu(data) {
  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 8000);
    const response = await fetch("/api/submit", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        ...data,
        submittedAt: new Date().toISOString()
      }),
      signal: controller.signal
    });
    clearTimeout(timer);
    const result = await response.json().catch(() => null);
    return !!(result && result.ok === true);
  } catch (err) {
    return false;
  }
}

function showSuccess(saved) {
  document.getElementById("leadForm").hidden = true;
  const panel = document.getElementById("successPanel");
  panel.hidden = false;
  document.getElementById("openAgain").setAttribute("href", lastWaUrl);

  const status = document.getElementById("backupStatus");
  status.hidden = false;
  if (saved) {
    status.textContent = t("ok.backupOk");
    status.classList.remove("is-error");
  } else {
    status.textContent = t("form.backupFailed");
    status.classList.add("is-error");
  }
  panel.scrollIntoView({ behavior: "smooth", block: "center" });
}

function resetForm() {
  const form = document.getElementById("leadForm");
  form.reset();
  fillSelects();
  getFieldMessages();
  form.hidden = false;
  document.getElementById("successPanel").hidden = true;
  form.scrollIntoView({ behavior: "smooth", block: "center" });
}

async function copyMessage() {
  const text = lastMessage || lastWaUrl;
  const copyBtn = document.getElementById("copyMessage");
  try {
    await navigator.clipboard.writeText(text);
  } catch (err) {
    const area = document.createElement("textarea");
    area.value = text;
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    document.execCommand("copy");
    area.remove();
  }
  copyBtn.textContent = t("ok.copied");
  setTimeout(() => {
    copyBtn.textContent = t("ok.copy");
  }, 2500);
}

function initForm() {
  const form = document.getElementById("leadForm");
  const submitBtn = form.querySelector('button[type="submit"]');
  const submitLabel = submitBtn.querySelector("span");

  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (!validateForm(form)) return;

    const data = collectData(form);
    const message = buildMessage(data);
    lastMessage = message;
    lastWaUrl = waUrl(message);

    submitBtn.disabled = true;
    submitLabel.textContent = t("form.sending");
    window.open(lastWaUrl, "_blank", "noopener");
    const saved = await backupToFeishu(data);
    submitBtn.disabled = false;
    submitLabel.textContent = t("form.submit");

    showSuccess(saved);
  });

  document.getElementById("copyMessage").addEventListener("click", copyMessage);
  document.getElementById("newRequest").addEventListener("click", resetForm);
}

function init() {
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });

  const floatingWa = document.getElementById("floatingWa");
  window.addEventListener("scroll", () => {
    floatingWa.classList.toggle("is-visible", window.scrollY > 500);
  }, { passive: true });

  applyLanguage(currentLang);
  initForm();
}

document.addEventListener("DOMContentLoaded", init);
